"""Copy the ISMS node to the Raspberry Pi and provision it.

    python deploy/deploy_pi.py            # sync code, then run setup
    python deploy/deploy_pi.py --sync     # sync code only (fast redeploy)

The Pi runs the same backend/ code as a laptop; only .env differs, because on
the Pi Ollama is local and the API must bind on all interfaces for the ESP32.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pi  # noqa: E402

HERE = Path(__file__).resolve().parent
BACKEND = HERE.parent / "backend"
APP = f"/home/{pi.USER}/isms"

FILES = [
    "server.py",
    "anomaly.py",
    "crack_detect.py",
    "ollama_client.py",
    "config.py",
    "hmi/index.html",
]
OPTIONAL = ["anomaly_model.pkl", "crack_model_int8.npz"]

PI_ENV = """# ISMS node config — Raspberry Pi 5 (generated by tools/deploy_pi.py)
# Ollama runs on this same Pi.
OLLAMA_HOST=http://127.0.0.1:11434
OLLAMA_MODEL=gemma4:e2b-it-qat
OLLAMA_TIMEOUT_S=180
OLLAMA_MIN_INTERVAL_S=90

# Bind on every interface so the ESP32-S3 can post to us.
PI_BIND_HOST=0.0.0.0
PI_PORT=8000
DASHBOARD_API_URL=http://127.0.0.1:8000

# Detection thresholds
CRACK_WARN=0.45
CRACK_CRITICAL=0.75
RUST_WARN=0.06

# Hull vision, calibrated on real frames from this node.
# Lower BREAK_CONTRAST_MIN if a genuine faint crack is being missed; raise it
# if cables or edges start registering as breaks.
BREAK_CONTRAST_MIN=38
BREAK_LEN_MIN=40
PLATE_MACRO_MAX=32
"""


def main() -> int:
    sync_only = "--sync" in sys.argv
    client = pi.connect()
    try:
        sftp = client.open_sftp()
        pi.mkdirs(sftp, APP)

        print("=== syncing code")
        for rel in FILES:
            local = BACKEND / rel
            if not local.exists():
                print(f"  !! missing {rel}")
                continue
            pi.put(sftp, local, f"{APP}/{rel}")
            print(f"  -> {rel} ({local.stat().st_size} B)")

        for rel in OPTIONAL:
            local = BACKEND / rel
            if local.exists():
                pi.put(sftp, local, f"{APP}/{rel}")
                print(f"  -> {rel} (optional)")

        pi.put_text(sftp, PI_ENV, f"{APP}/.env")
        print("  -> .env (Pi flavour)")
        pi.mkdirs(sftp, f"{APP}/data")

        if sync_only:
            code, out = pi.run(client, "sudo -n systemctl restart isms-api; sleep 5; "
                                       "systemctl is-active isms-api; "
                                       "curl -s --max-time 8 http://127.0.0.1:8000/health | head -c 300")
            print("\n=== restart\n" + out)
            return 0

        print("\n=== provisioning (this can take a few minutes)")
        setup = f"/home/{pi.USER}/pi_setup.sh"
        pi.put_script(sftp, HERE / "pi_setup.sh", setup)
        code, out = pi.run(
            client,
            f"PI_PASS={pi._q(pi.PASS)} bash {setup}",
            timeout=1800,
        )
        print(out)
        return code
    finally:
        client.close()


if __name__ == "__main__":
    sys.exit(main())
